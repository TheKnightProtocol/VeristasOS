function getLanguageCode(langName) {
    if (!langName) return "en";
    const nameLower = langName.toLowerCase();

    if (nameLower.includes("hind") || nameLower === "हिन्दी" || nameLower === "hi") return "hi";
    if (nameLower.includes("hinglish")) return "hinglish";
    if (nameLower.includes("bengal") || nameLower === "বাংলা" || nameLower === "bn") return "bn";
    if (nameLower.includes("telugu") || nameLower === "తెలుగు" || nameLower === "te") return "te";
    if (nameLower.includes("marath") || nameLower === "मराठी" || nameLower === "mr") return "mr";
    if (nameLower.includes("tamil") || nameLower === "தமிழ்" || nameLower === "ta") return "ta";
    if (nameLower.includes("gujarat") || nameLower === "ગુજરાતી" || nameLower === "gu") return "gu";
    if (nameLower.includes("kannad") || nameLower === "ಕನ್ನಡ" || nameLower === "kn") return "kn";
    if (nameLower.includes("malayal") || nameLower === "മലയാളം" || nameLower === "ml") return "ml";
    if (nameLower.includes("punjab") || nameLower === "ਪੰਜਾਬੀ" || nameLower === "pa") return "pa";
    if (nameLower.includes("odia") || nameLower === "ଓଡ଼ିଆ" || nameLower === "or") return "or";
    if (nameLower.includes("assame") || nameLower === "অসমীয়া" || nameLower === "as") return "as";
    if (nameLower.includes("urdu") || nameLower === "اردو" || nameLower === "ur") return "ur";
    if (nameLower.includes("auto")) return "auto";

    return "en";
}

function applyI18n(langName) {
    const code = getLanguageCode(langName);
    const dict = TRANSLATIONS[code] || TRANSLATIONS.en;

    // Handle RTL direction for Urdu
    if (code === "ur") {
        document.documentElement.setAttribute("dir", "rtl");
        document.documentElement.classList.add("rtl-mode");
    } else {
        document.documentElement.setAttribute("dir", "ltr");
        document.documentElement.classList.remove("rtl-mode");
    }

    // Translate all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Translate placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
            el.setAttribute("placeholder", dict[key]);
        }
    });

    // Store in localStorage
    localStorage.setItem("veristasos_language", langName);
}
